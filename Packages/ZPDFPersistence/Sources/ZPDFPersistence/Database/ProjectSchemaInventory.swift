import Foundation
import GRDB

/// The exact set of schema objects a Zenit PDF project database may contain, and the
/// check that refuses anything else (S17-09).
///
/// ### The problem
///
/// `project.sqlite` arrives inside a document. `PRAGMA integrity_check` answers "are the
/// b-trees intact", not "did we write this schema", so a `.zpdfproj` that came by mail
/// can carry a trigger, a view, a `CHECK` constraint or a generated column — SQL text
/// stored *in the schema* — that SQLite then evaluates inside our own transactions, on
/// our own thread, against the user's takeoff rows.
///
/// ### Why an allow-list, and not something cheaper
///
/// Three defences were considered and measured against what SQLite actually offers:
///
/// 1. **`PRAGMA trusted_schema = OFF`** (landed earlier, S17-06). It stops schema SQL
///    calling functions that are not marked innocuous. It does *not* stop a trigger
///    from running `INSERT`, `UPDATE`, `DELETE` or `RAISE`, which is the whole of the
///    realistic attack here. Necessary, nowhere near sufficient.
/// 2. **Open untrusted databases in a mode where schema objects cannot execute.** There
///    is no such mode. `SQLITE_DBCONFIG_DEFENSIVE` forbids `writable_schema` and direct
///    shadow-table writes; it leaves triggers and views running. The one mode that does
///    stop a trigger firing is *read-only* — a trigger needs a write to fire — and an
///    application that can only ever open a project read-only is not an application.
///    Read-only therefore survives here as the **escape hatch**, not as the defence:
///    a project this check refuses can still be inspected through
///    ``ProjectPackage/AccessMode/readOnly``, where nothing of the attacker's can run.
/// 3. **Enumerate and reject.** Compare `sqlite_master` against exactly what
///    ``ProjectSchema``'s migrations create and refuse anything else. This is the one
///    that closes the class rather than an instance of it, and it is what is
///    implemented below.
///
/// ### Recognising our own triggers exactly
///
/// A blanket "no triggers" rule is not available: ADR-0007's append-only audit trail is
/// *enforced* by two triggers, and they are in every project from schema v2 onwards. So
/// the rule cannot be about the object's type, it has to be about its identity. Every
/// expected object is matched by **name and by whitespace-normalised definition**, taken
/// from the very strings the migrations execute — so a trigger of the right name whose
/// body has grown a `WHEN` clause that quietly disarms the `RAISE(ABORT)` is refused as
/// loudly as a trigger nobody has ever seen. And, because dropping them is the other way
/// to defeat append-only, a database that has the `measurement_audit` table must have
/// both of its triggers.
///
/// ### What is deliberately tolerated
///
/// - Objects **missing** relative to the current schema. An older project legitimately
///   has fewer tables; the migrator's job is to add them. Only *extra* and *altered*
///   objects are refusals.
/// - `sqlite_`-prefixed indexes whose `sql` is `NULL`. Those are SQLite's own implicit
///   unique indexes: they carry no SQL, so there is nothing in them to execute.
/// - `grdb_migrations`, GRDB's bookkeeping table, whose contents are separately gated by
///   ``ProjectSchema/assertCompatible(_:)``.
/// - FTS5's five shadow tables for `search_fts`. Their definitions are generated by the
///   FTS5 extension rather than by us, and they are matched against the exact text this
///   toolchain's SQLite produces — pinned, like everything else here, by `TOOLCHAIN.md`.
///   `HostileProjectPackageTests.aFreshlyMigratedDatabaseHasNothingForeignInIt` is what fails, on
///   the first run after a toolchain bump, if that text ever changes.
public enum ProjectSchemaInventory {

    // MARK: - Deviations

    /// One reason a database's schema is not the schema this build writes.
    public struct Deviation: Sendable, Hashable {
        public enum Kind: String, Sendable, Hashable {
            /// An object no migration in this build creates.
            case foreign
            /// An object of ours, under the right name, with the wrong definition.
            case altered
            /// An object of ours that must be present and is not.
            case absent
        }

        public let kind: Kind
        /// `table`, `index`, `trigger` or `view`, as `sqlite_master` spells it.
        public let objectType: String
        public let name: String
        /// What was found, for the report and for the test that names the reason.
        public let detail: String

        public init(kind: Kind, objectType: String, name: String, detail: String) {
            self.kind = kind
            self.objectType = objectType
            self.name = name
            self.detail = detail
        }

        /// The typed refusal this deviation becomes on a read-write open.
        public var error: ZPDFPersistenceError {
            switch kind {
            case .foreign:
                return .foreignSchemaObject(objectType: objectType, name: name)
            case .altered, .absent:
                return .schemaObjectAltered(objectType: objectType, name: name)
            }
        }
    }

    // MARK: - The expected schema

    /// Every `CREATE TABLE` this build's migrations execute, keyed by table name.
    ///
    /// Values are **sets**, because a table can have more than one legitimate spelling in a
    /// project this build is willing to open. `ALTER TABLE ADD COLUMN` rewrites the stored SQL,
    /// so v8's `stamp_artwork` reads differently from v7's — and the guard runs *before* the
    /// migrator, deliberately, so a genuine v7 project still carries the v7 spelling when it is
    /// checked. Accepting only the newest form would refuse every project written before this
    /// build as hostile. This is the same reasoning ``expectedIndexSQL`` gives for keeping v2's
    /// dropped audit index in its set.
    public static let expectedTableSQL: [String: Set<String>] = {
        var statements = ProjectSchema.coreTableStatements
        statements.append(ProjectSchema.auditTableStatement)
        statements.append(ProjectSchema.layerOverrideTableStatement)
        statements.append(contentsOf: ProjectSchema.takeoffHydrationTableStatements)
        statements.append(contentsOf: ProjectSchema.projectStructureTableStatements)
        statements.append(contentsOf: ProjectSchema.stampTableStatements)
        statements.append(ProjectSchema.markupSymbolTableStatement)
        statements.append(ProjectSchema.pageScaleTableStatement)
        statements.append(ProjectSchema.reviewEntryTableStatement)
        statements.append(contentsOf: ProjectSchema.documentSetTableStatements)
        statements.append(ProjectSchema.ledgerSnapshotTableStatement)
        statements.append(ProjectSchema.authorTableStatement)
        statements.append(ProjectSchema.automationProposalTableStatement)
        statements.append(ProjectSchema.markupLayerTableStatement)      // v18, ADR-0032
        statements.append(ProjectSchema.projectSettingTableStatement)   // v18, ADR-0032
        var result: [String: Set<String>] = [:]
        for statement in statements {
            guard let name = tableName(inCreateStatement: statement) else { continue }
            result[name, default: []].insert(normalized(statement))
        }
        result["stamp_artwork", default: []]
            .insert(normalized(ProjectSchema.stampArtworkTableStatementAfterV8))
        result["markup_extra", default: []]
            .insert(normalized(ProjectSchema.markupExtraTableStatementAfterV10))
        result["markup_extra", default: []]
            .insert(normalized(ProjectSchema.markupExtraTableStatementAfterV17))
        result["markup_extra", default: []]
            .insert(normalized(ProjectSchema.markupExtraTableStatementAfterV18))
        result["custom_column", default: []]
            .insert(normalized(ProjectSchema.customColumnTableStatementAfterV11))
        result["page_set_entry", default: []]
            .insert(normalized(ProjectSchema.pageSetEntryTableStatementAfterV15))
        return result
    }()

    /// Every `CREATE INDEX` any migration in this build's history creates, keyed by name.
    ///
    /// History, not current state, and that distinction is load-bearing: migration v4
    /// *drops* v2's `idx_measurement_audit_markup_sequence` and replaces it with the
    /// UNIQUE index, so a genuine pre-v4 project still carries the old one when this
    /// check runs — the guard runs before the migrator, deliberately. Keeping it in the
    /// expected set is what stops a legitimate old project being refused as hostile. The
    /// converse is already safe: a *missing* object is never a refusal.
    public static let expectedIndexSQL: [String: String] = {
        var definitions = ProjectSchema.indexDefinitions
        definitions.append(contentsOf: ProjectSchema.auditIndexDefinitions)
        definitions.append(ProjectSchema.auditUniqueMarkupSequenceIndex)
        definitions.append(contentsOf: ProjectSchema.layerOverrideIndexDefinitions)
        definitions.append(contentsOf: ProjectSchema.takeoffHydrationIndexDefinitions)
        definitions.append(contentsOf: ProjectSchema.projectStructureIndexDefinitions)
        definitions.append(contentsOf: ProjectSchema.stampIndexDefinitions)
        definitions.append(contentsOf: ProjectSchema.markupSymbolIndexDefinitions)
        definitions.append(contentsOf: ProjectSchema.pageScaleIndexDefinitions)
        definitions.append(contentsOf: ProjectSchema.reviewEntryIndexDefinitions)
        definitions.append(contentsOf: ProjectSchema.documentSetIndexDefinitions)
        definitions.append(contentsOf: ProjectSchema.ledgerSnapshotIndexDefinitions)
        definitions.append(contentsOf: ProjectSchema.authorIndexDefinitions)
        definitions.append(contentsOf: ProjectSchema.automationProposalIndexDefinitions)
        var result: [String: String] = [:]
        for definition in definitions {
            result[definition.name] = normalized(definition.sql)
        }
        return result
    }()

    /// The only triggers a Zenit PDF project may contain: ADR-0007's append-only pair.
    public static let expectedTriggerSQL: [String: String] = {
        var result: [String: String] = [:]
        for statement in ProjectSchema.auditTriggerStatements {
            guard let name = triggerName(inCreateStatement: statement) else { continue }
            result[name] = normalized(statement)
        }
        return result
    }()

    /// The table whose presence makes the audit triggers mandatory.
    public static let auditTableName = "measurement_audit"

    /// GRDB's migration bookkeeping table, created by `DatabaseMigrator` rather than by
    /// a statement of ours. Its *contents* are gated by ``ProjectSchema/assertCompatible(_:)``.
    public static let grdbMigrationsTableSQL =
        "CREATE TABLE grdb_migrations (identifier TEXT NOT NULL PRIMARY KEY)"

    /// The five shadow tables FTS5 creates for `search_fts`, as this toolchain's SQLite
    /// spells them.
    public static let fts5ShadowTableSQL: [String: String] = [
        "search_fts_data": "CREATE TABLE 'search_fts_data'(id INTEGER PRIMARY KEY, block BLOB)",
        "search_fts_idx":
            "CREATE TABLE 'search_fts_idx'(segid, term, pgno, PRIMARY KEY(segid, term)) WITHOUT ROWID",
        "search_fts_content":
            "CREATE TABLE 'search_fts_content'(id INTEGER PRIMARY KEY, c0, c1, c2, c3, c4, c5)",
        "search_fts_docsize": "CREATE TABLE 'search_fts_docsize'(id INTEGER PRIMARY KEY, sz BLOB)",
        "search_fts_config": "CREATE TABLE 'search_fts_config'(k PRIMARY KEY, v) WITHOUT ROWID"
    ]

    // MARK: - The check

    /// Every way the database at hand differs from the schema this build writes.
    ///
    /// Read-only, cheap — one scan of `sqlite_master`, which is a handful of rows — and
    /// safe to run before the migrator, which is where it is run from: the point is to
    /// refuse *before* a write of ours can make somebody else's trigger fire.
    public static func deviations(in db: Database) throws -> [Deviation] {
        let rows = try Row.fetchAll(
            db,
            sql: "SELECT type, name, sql FROM sqlite_master ORDER BY type, name"
        )
        var found: [Deviation] = []
        var sawAuditTable = false
        var seenTriggers: Set<String> = []

        for row in rows {
            let objectType: String = row["type"] ?? ""
            let name: String = row["name"] ?? ""
            let sql: String? = row["sql"]

            switch objectType {
            case "table":
                if name == auditTableName { sawAuditTable = true }
                if let expected = expectedTableSQL[name] {
                    if !expected.contains(normalized(sql ?? "")) {
                        found.append(.init(
                            kind: .altered, objectType: "table", name: name,
                            detail: "the table definition is not the one this build creates"
                        ))
                    }
                    continue
                }
                if name == "grdb_migrations" {
                    if normalized(sql ?? "") != normalized(grdbMigrationsTableSQL) {
                        found.append(.init(
                            kind: .altered, objectType: "table", name: name,
                            detail: "GRDB's migration table has been redefined"
                        ))
                    }
                    continue
                }
                if let shadow = fts5ShadowTableSQL[name] {
                    if normalized(sql ?? "") != normalized(shadow) {
                        found.append(.init(
                            kind: .altered, objectType: "table", name: name,
                            detail: "an FTS5 shadow table has been redefined"
                        ))
                    }
                    continue
                }
                if name.hasPrefix("sqlite_") { continue }
                found.append(.init(
                    kind: .foreign, objectType: "table", name: name,
                    detail: "no migration in this build creates a table with this name"
                ))

            case "index":
                if let expected = expectedIndexSQL[name] {
                    if normalized(sql ?? "") != expected {
                        found.append(.init(
                            kind: .altered, objectType: "index", name: name,
                            detail: "the index definition is not the one this build creates"
                        ))
                    }
                    continue
                }
                // SQLite's own implicit unique indexes. They carry no SQL at all, so
                // there is no stored expression in them for anyone to hide anything in;
                // one that *does* carry SQL was written by hand and is refused.
                if name.hasPrefix("sqlite_"), sql == nil { continue }
                found.append(.init(
                    kind: .foreign, objectType: "index", name: name,
                    detail: "no migration in this build creates an index with this name"
                ))

            case "trigger":
                seenTriggers.insert(name)
                guard let expected = expectedTriggerSQL[name] else {
                    found.append(.init(
                        kind: .foreign, objectType: "trigger", name: name,
                        detail: "Zenit PDF creates exactly two triggers and this is neither"
                    ))
                    continue
                }
                if normalized(sql ?? "") != expected {
                    found.append(.init(
                        kind: .altered, objectType: "trigger", name: name,
                        detail: "an append-only audit trigger no longer has its ADR-0007 definition"
                    ))
                }

            case "view":
                // Zenit PDF creates no views at all, so every view is somebody else's.
                found.append(.init(
                    kind: .foreign, objectType: "view", name: name,
                    detail: "Zenit PDF creates no views"
                ))

            default:
                found.append(.init(
                    kind: .foreign, objectType: objectType, name: name,
                    detail: "unrecognised sqlite_master object type"
                ))
            }
        }

        // Dropping the append-only triggers is the other half of tampering with the
        // audit trail, and it leaves nothing extra behind for the loop above to see.
        if sawAuditTable {
            for name in expectedTriggerSQL.keys.sorted() where !seenTriggers.contains(name) {
                found.append(.init(
                    kind: .absent, objectType: "trigger", name: name,
                    detail: "the append-only audit trigger ADR-0007 requires has been removed"
                ))
            }
        }
        return found
    }

    // MARK: - Text handling

    /// Whitespace-collapsed, semicolon-trimmed SQL.
    ///
    /// `sqlite_master.sql` stores the statement text as it was executed, so a comparison
    /// against the migration's own string is exact up to the line breaks and indentation
    /// that Swift's multi-line literals carry. Nothing else is normalised: case is
    /// significant, identifier quoting is significant, and a `WHEN` clause that was not
    /// there before is a mismatch, which is the entire point.
    public static func normalized(_ sql: String) -> String {
        let collapsed = sql.split(whereSeparator: { $0.isWhitespace }).joined(separator: " ")
        return collapsed.hasSuffix(";") ? String(collapsed.dropLast()) : collapsed
    }

    private static func tableName(inCreateStatement statement: String) -> String? {
        identifier(after: ["CREATE", "TABLE"], in: statement)
            ?? identifier(after: ["CREATE", "VIRTUAL", "TABLE"], in: statement)
    }

    private static func triggerName(inCreateStatement statement: String) -> String? {
        identifier(after: ["CREATE", "TRIGGER"], in: statement)
    }

    /// The word following a fixed keyword prefix, with any trailing `(` stripped.
    private static func identifier(after keywords: [String], in statement: String) -> String? {
        let words = statement.split(whereSeparator: { $0.isWhitespace }).map(String.init)
        guard words.count > keywords.count else { return nil }
        for (index, keyword) in keywords.enumerated() where words[index].uppercased() != keyword {
            return nil
        }
        let candidate = words[keywords.count]
        return String(candidate.prefix(while: { $0 != "(" }))
    }
}
