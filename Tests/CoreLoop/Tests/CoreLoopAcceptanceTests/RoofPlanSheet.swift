/// Shorthand for a presentation point.
func PDFPointValueXY(_ x: Double, _ y: Double) -> PDFPointValue {
    PDFPointValue(x: x, y: y)
}

/// SHA-256 of a file's bytes, computed here with CryptoKit so the assertion does not share
/// code with the bridge's own digest.
func independentSHA256(of url: URL) throws -> (hex: String, byteCount: Int) {
    let data = try Data(contentsOf: url)
    let digest = SHA256.hash(data: data)
    return (digest.map { String(format: "%02x", $0) }.joined(), data.count)
}

/// Polls a main-actor condition until it holds or the deadline passes.
@MainActor
func eventually(
    _ what: String,
    timeout: Duration = .seconds(15),
    condition: @MainActor () async -> Bool
) async throws {
    let clock = ContinuousClock()
    let deadline = clock.now.advanced(by: timeout)
    while clock.now < deadline {
        if await condition() { return }
        try await Task.sleep(for: .milliseconds(20))
    }
    Issue.record("timed out after \(timeout) waiting for \(what)")
}

/// Counts the user-visible actions of one CORE_LOOP step — the clicks and keystrokes a
/// real user would spend — so a budget overrun is a test failure, not an opinion.
struct ActionCounter {
    let step: String
    private(set) var actions: [String] = []
    var count: Int { actions.count }

    init(step: String) { self.step = step }

    mutating func tap(_ action: String) { actions.append(action) }

    func assertWithinBudget(_ budget: Int) {
        #expect(
            count <= budget,
            "\(step) took \(count) user actions (\(actions.joined(separator: " → "))); CORE_LOOP allows \(budget)"
        )
    }
}

/// A minimal RFC 4180 reader for the files this test itself exports: CRLF records,
/// double-quote escaping, an optional UTF-8 BOM, and the delimiter the file was written with
/// (BH-915: `LedgerCSVExport.write` uses `;` where the decimal separator is a comma).
enum CSVReader {
    static func parse(_ text: String, delimiter: Character = ",") -> [[String]] {
        var input = Substring(text)
        if input.hasPrefix("\u{FEFF}") { input = input.dropFirst() }
        var records: [[String]] = []
        var record: [String] = []
        var field = ""
        var inQuotes = false
        var index = input.startIndex
        func endField() { record.append(field); field = "" }
        func endRecord() { endField(); records.append(record); record = [] }
        while index < input.endIndex {
            let character = input[index]
            if inQuotes {
                if character == "\"" {
                    let next = input.index(after: index)
                    if next < input.endIndex, input[next] == "\"" {
                        field.append("\"")
                        index = next
                    } else {
                        inQuotes = false
                    }
                } else {
                    field.append(character)
                }
            } else {
                switch character {
                case "\"": inQuotes = true
                case delimiter: endField()
                // Swift folds CRLF into one `Character`, so "\r\n" is its own case — the
                // same trap the product's CSV escaper documents.
                case "\r\n", "\r", "\n": endRecord()
                default: field.append(character)
                }
            }
            index = input.index(after: index)
        }
        if !field.isEmpty || !record.isEmpty { endRecord() }
        return records
    }
}
