/// The sheet the loop is walked on, and every hand-derived fact about it the acceptance test uses.
///
/// # The drawing
///
/// `synthetic-roof-plan.pdf` — the Synthetic Roof Plan of `ZPDFTestingSupport`
/// (`SyntheticRoofPlan`, `FIXTURES.md`): one A1 landscape vector page, crop box
/// 2383.94 × 1683.78 pt, 16 341 extractable vector primitives, no PDF layers, a fictional title
/// block (DEMO ROOF, A-00-0-001, SKALA 1:50). It is generated by the test, byte for byte the same
/// on every machine, and its identity is versioned: ``identityName`` and ``sha256`` are pinned
/// here, in `SyntheticRoofPlan`, and in `Scripts/acceptance-core-loop.sh`. A change to the
/// generator that moves one byte bumps the version and every pin with it.
///
/// # The calibration dimension, and why this one
///
/// The sheet prints no dimension chains. What it does carry, printed for exactly this purpose,
/// is a 100 mm measurement-control ruler at its foot: a base line with eleven ticks 10 mm apart.
/// The title block prints `SKALA 1:50` and the notes say dimensions are in millimetres, so the
/// one dimension of known real value on the sheet is the ruler itself:
///
///     100 mm of paper × 50  =  5 000 mm  =  5.000 m of building
///
/// 100 mm of paper is 100 × 72 / 25.4 = 36000 / 127 = 283.46456692913387 pt, and that is the
/// length the ruler is drawn at (the constant `SyntheticRoofPlan.rulerLength`).
///
/// # The anchor geometry (from `SyntheticRoofPlan`, the coordinates the file is written with)
///
/// The ruler's base line is one `lineSegment` primitive from (1050, 42) to
/// (1050 + 36000/127, 42) = (1333.464566929134, 42), and each of the eleven tick lines runs
/// vertically from y 42 to y 42 + 1800/127 at x = 1050 + 3600·k/127.
enum RoofPlanSheet {

    /// The versioned identity the generated file must have.
    static let identityName = SyntheticRoofPlan.identityName
    static let sha256 = SyntheticRoofPlan.sha256
    static let byteCount = SyntheticRoofPlan.byteCount

    /// Writes the sheet into `directory` — a fresh scratch directory per run, so nothing else can
    /// share or touch the file this test hashes before and after — and returns its location.
    static func generate(in directory: URL) throws -> URL {
        try ZPDFFixtures.make(.syntheticRoofPlan, in: directory).url
    }

    /// The vector primitives the extractor must find: counted by hand from the drawing's
    /// construction (`FIXTURES.md`), never by running an extractor.
    static let primitiveCount = 16_341

    /// Crop box, from the page dictionary.
    static let cropWidth = 2383.94
    static let cropHeight = 1683.78

    // MARK: Calibration anchors

    /// Foot of the ruler's leftmost tick — where base line and first tick meet.
    static let stripLeft = PDFPoint(x: 1050, y: 42)
    /// Foot of the ruler's rightmost tick: 1050 + 36000/127, one correctly rounded addition.
    static let stripRight = PDFPoint(x: 1333.464566929134, y: 42)
    /// The value the user types after the two clicks: the strip is 100 mm of paper on a
    /// 1:50 sheet whose measurements are in millimetres.
    static let knownLengthMillimetres = Decimal(5000)

    /// Where the two calibration clicks land — a couple of points off each tick foot, well
    /// inside the 10 px snap radius (5 pt at zoom 1 on a 2× display), so the anchor comes
    /// from the snap engine, not from the click.
    static let clickNearLeft = PDFPoint(x: 1052, y: 44)
    static let clickNearRight = PDFPoint(x: 1331.5, y: 44)

    /// metres per PDF point the calibration must produce:
    ///     Δx = 1333.464566929134 − 1050 = 283.464566929134 pt
    ///     mpp = 5.0 m / 283.464566929134 pt = 0.01763888888888888 m/pt
    /// which is 1.27/72 to the last bit but one — the sheet's printed `SKALA 1:50` exactly.
    static var stripPoints: Double { stripRight.x - stripLeft.x }
    static var metresPerPoint: Double { 5.0 / stripPoints }

    // MARK: Picked measurement coordinates

    /// All picked vertices sit in the sheet's free measuring band (`SyntheticRoofPlan.freeBand`,
    /// x 1720…2045, y 520…1200), which no drawn primitive comes within 40 pt of except the title
    /// column's divider at x = 2050 — 21.5 pt beyond the furthest pick — so a snap (radius 5 pt at
    /// the layout used) can never silently move a vertex the hand-derivation relies on. They keep
    /// at least 6 pt from every 36 pt grid line as well.
    ///
    /// Polyline "Roof edge": two axis-aligned segments, one ruler and half a ruler long.
    ///     A (1745, 890) → B (2028.464566929134, 890)    Δx = 283.464566929134 pt
    ///     B → C (2028.464566929134, 1031.732283464567)  Δy = 141.73228346456693 pt
    /// Hand-derivation:
    ///     seg1 = 283.464566929134 × mpp = 5.0 m
    ///     seg2 = 141.73228346456693 × mpp = 2.5 m
    ///     planLength = 7.5 m → displays "7.50" m at 2 decimals
    static let polyA = PDFPointValueXY(1745, 890)
    static let polyB = PDFPointValueXY(2028.464566929134, 890)
    static let polyC = PDFPointValueXY(2028.464566929134, 1031.732283464567)
    static let expectedPolylineMetres = 7.5
    static let expectedPolylineText = "7.50"

    /// Polygon "Roof plane": axis-aligned rectangle.
    ///     (1745, 600) → (2028.464566929134, 770.0787401574803)
    ///     w = 283.464566929134 pt × mpp = 5.0 m
    ///     h = 170.0787401574803 pt × mpp = 2.9999999999999982 m   (0.6 × the strip)
    /// Hand-derivation (shoelace of an axis-aligned rectangle = w × h):
    ///     planArea  = 14.999999999999991 m² → displays "15.00" m²
    ///     perimeter = 15.999999999999996 m  → displays "16.00" m
    static let rectRing = [
        PDFPointValueXY(1745, 600),
        PDFPointValueXY(2028.464566929134, 600),
        PDFPointValueXY(2028.464566929134, 770.0787401574803),
        PDFPointValueXY(1745, 770.0787401574803)
    ]
    static let expectedRectAreaSquareMetres = 14.999999999999991
    static let expectedRectAreaText = "15.00"
    static let expectedRectPerimeterText = "16.00"

    /// Cutout "Roof opening" inside the rectangle.
    ///     (1802, 655) → (1858.6929133858268, 683.3464566929134)
    ///     w = 56.69291338582678 pt × mpp = 1.0000000000000009 m   (0.2 × the strip)
    ///     h = 28.346456692913407 pt × mpp = 0.5000000000000004 m  (0.1 × the strip)
    ///     cutout area = 0.5000000000000009 m² → displays "0.50" m²
    ///     net area    = 15.0 − 0.5 = 14.49999999999999 m²
    static let cutoutRing = [
        PDFPointValueXY(1802, 655),
        PDFPointValueXY(1858.6929133858268, 655),
        PDFPointValueXY(1858.6929133858268, 683.3464566929134),
        PDFPointValueXY(1802, 683.3464566929134)
    ]
    static let expectedCutoutAreaSquareMetres = 0.5000000000000009
    static let expectedCutoutAreaText = "0.50"
    static let expectedNetAreaSquareMetres = 14.49999999999999

    /// What the ledger's Plan Area column shows for "Roof plane" (ADR-0016: Plan Area reads
    /// the net area, outline minus the union of its cutouts):
    ///     net = 14.999999999999991 − 0.5000000000000009 = 14.49999999999999 m²
    ///     rounded once to 2 decimals → "14.50" (the gross 15.00 is no longer the quantity)
    static let expectedNetAreaText = "14.50"

    /// What the ledger shows in every quantity cell of the cutout row "Roof opening"
    /// (ADR-0018: a cutout is part of its parent, never a quantity of its own; under the
    /// default `subtractFromArea` not even Cutout Area is reported on its row): nothing.
    /// Before ADR-0016 this cell read the cutout's own "0.50".
    static let expectedCutoutRowAreaText = ""

    /// The double-rounding probe, "Rounding probe": one horizontal segment whose length in
    /// metres falls in the trap window (0.4445, 0.44495):
    ///     (1745, 1100) → (1770.2114, 1100)
    ///     Δx = 25.2114 pt × mpp = 0.4447010833333316 m
    /// Rounded once, at the boundary, to 2 decimals: **0.44**.
    /// Rounded twice (3 decimals, then 2): 0.445 → **0.45** — the wrong digit this probe
    /// exists to catch (QUALITY_BAR A31, silent-wrongness list item 5).
    static let probeA = PDFPointValueXY(1745, 1100)
    static let probeB = PDFPointValueXY(1770.2114, 1100)
    static let expectedProbeMetres = 0.4447010833333316
    static let expectedProbeText = "0.44"
    static let expectedProbeDoubleRoundedText = "0.45"

    /// Grand totals over the four rows above:
    ///     planLength = 7.5 + 0.4447010833333316 = 7.944701083333332 m
    ///                  → "7.94" (double-rounded it would be 7.945 → "7.95")
    ///     planArea   = the roof plane's net 14.49999999999999 m² + nothing from the cutout
    ///                  row (ADR-0016/0018) = 14.49999999999999 m² → "14.50".
    ///                  Before ADR-0016: gross 15.0 + cutout 0.5 = 15.5 → "15.50", the opening
    ///                  counted as area *added* to the roof.
    static let expectedLengthTotalText = "7.94"
    static let expectedLengthTotalDoubleRoundedText = "7.95"
    static let expectedAreaTotalText = "14.50"

    /// The stale-geometry probe edit: the probe's far vertex is dragged to
    ///     (1795.4228, 1100)  →  Δx = 50.4228 pt × mpp = 0.8894021666666672 m
    /// The row must show "0.89" the moment the geometry lands — never the stale "0.44" —
    /// and the length total becomes 8.389402166666667 → "8.39".
    static let probeBMoved = PDFPointValueXY(1795.4228, 1100)
    static let expectedMovedProbeText = "0.89"
    static let expectedMovedLengthTotalText = "8.39"
}

